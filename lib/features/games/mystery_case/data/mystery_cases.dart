  static List<MysteryCase> session({int count = 4, GameDifficulty? difficulty, String? topic}) {
    List<MysteryCase> pool = all;
    if (difficulty != null) pool = pool.where((c) => c.difficulty == difficulty).toList();
    if (topic != null) pool = pool.where((c) => c.topic == topic).toList();
    final sorted = [...pool]..sort((a, b) => a.id.compareTo(b.id));
    if (sorted.length <= count) return sorted;
    return sorted.take(count).toList();
  }

