  static List<BossBattle> session({int count = 4, GameDifficulty? difficulty, String? topic}) {
    List<BossBattle> pool = all;
    if (difficulty != null) pool = pool.where((b) => b.difficulty == difficulty).toList();
    if (topic != null) pool = pool.where((b) => b.topic == topic).toList();
    final sorted = [...pool]..sort((a, b) => a.id.compareTo(b.id));
    if (sorted.length <= count) return sorted;
    return sorted.take(count).toList();
  }

  static List<BossBattle> forDifficulty(GameDifficulty d) => all.where((b) => b.difficulty == d).toList();
  static List<BossBattle> forTopic(String t) => all.where((b) => b.topic == t).toList();
