  static List<ConnectivityMission> session({int count = 4, GameDifficulty? difficulty, String? topic, MissionType? type}) {
    List<ConnectivityMission> pool = all;
    if (difficulty != null) pool = pool.where((m) => m.difficulty == difficulty).toList();
    if (topic != null) pool = pool.where((m) => m.topic == topic).toList();
    if (type != null) pool = pool.where((m) => m.missionType == type).toList();
    final sorted = [...pool]..sort((a, b) => a.id.compareTo(b.id));
    if (sorted.length <= count) return sorted;
    return sorted.take(count).toList();
  }

  static List<ConnectivityMission> forDifficulty(GameDifficulty d) => all.where((m) => m.difficulty == d).toList();
  static List<ConnectivityMission> forType(MissionType t) => all.where((m) => m.missionType == t).toList();
}
