  static List<PuzzleArenaPuzzle> session({int count = 4, GameDifficulty? difficulty, String? topic, PuzzleType? type}) {
    List<PuzzleArenaPuzzle> pool = all;
    if (difficulty != null) pool = pool.where((p) => p.difficulty == difficulty).toList();
    if (topic != null) pool = pool.where((p) => p.topic == topic).toList();
    if (type != null) pool = pool.where((p) => p.puzzleType == type).toList();
    final sorted = [...pool]..sort((a, b) => a.id.compareTo(b.id));
    if (sorted.length <= count) return sorted;
    return sorted.take(count).toList();
  }

  static List<PuzzleArenaPuzzle> forDifficulty(GameDifficulty d) => all.where((p) => p.difficulty == d).toList();
  static List<PuzzleArenaPuzzle> forType(PuzzleType t) => all.where((p) => p.puzzleType == t).toList();
}
